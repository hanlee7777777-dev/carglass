function __isRealLink(el){ var h = el.tagName === 'A' ? (el.getAttribute('href') || '') : ''; return !!h && h.indexOf('javascript:') !== 0; }
function __bindNoticeTriggers(){
  document.querySelectorAll('[data-open]').forEach(function(el){
    if(el.__bound || __isRealLink(el)) return; el.__bound=true;
    el.addEventListener('click', function(e){
      e.preventDefault();
      e.stopPropagation();
      var c=el.getAttribute('data-close');
      if(c){ var _sid=(c==='1')?'subPage':'subPage'+c; var _sEl=document.getElementById(_sid); if(_sEl){ _sEl.style.display='none'; _sEl.classList.remove('open'); _sEl.setAttribute('aria-hidden','true'); } }
      var n=el.getAttribute('data-open');
      if(__openFns[n]) __openFns[n]();
      requestAnimationFrame(function(){
        requestAnimationFrame(function(){
          document.querySelectorAll('.qBtnRow .qBtn').forEach(function(b){ void b.offsetWidth; });
          __restartQBtnAnim();
        });
      });
      setTimeout(__restartQBtnAnim, 50);
      setTimeout(function(){
        document.querySelectorAll('.qBtnRow .qBtn').forEach(function(b){ void b.offsetWidth; });
      }, 200);
      setTimeout(function(){
        document.querySelectorAll('.qBtnRow .qBtn').forEach(function(b){ void b.offsetWidth; });
        __restartQBtnAnim();
      }, 500);
    });
  });
  document.querySelectorAll('[data-close]').forEach(function(el){
    if(el.__bound || __isRealLink(el)) return; el.__bound=true;
    el.addEventListener('click', function(e){
      e.preventDefault();
      var n=el.getAttribute('data-close');
      if(__closeFns[n]) __closeFns[n]();
    });
  });
  document.querySelectorAll('[data-jump]').forEach(function(el){
    if(el.__bound || __isRealLink(el)) return; el.__bound=true;
    el.addEventListener('click', function(e){
      e.preventDefault();
      var n=el.getAttribute('data-jump');
      __jumpTo(n);
      setTimeout(__restartQBtnAnim, 50);
    });
  });
  document.querySelectorAll('[data-home]').forEach(function(el){
    if(el.__bound || __isRealLink(el)) return; el.__bound=true;
    el.addEventListener('click', function(e){
      e.preventDefault();
      __goHome();
    });
  });
}
