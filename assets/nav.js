function __showSubFromHash(){
  if(document.body.hasAttribute('data-standalone')) return;
  __closeAllSub();
  var h = location.hash;
  if(h && h.indexOf('#sub')===0){
    var n = h.slice(4);
    var id = (n==='1') ? 'subPage' : 'subPage'+n;
    var s = document.getElementById(id);
    if(s){
      if(id==='subPage'){ s.classList.add('open'); s.setAttribute('aria-hidden','false'); }
      else { s.style.display='block'; s.setAttribute('aria-hidden','false'); }
      document.body.classList.add('subOpen');
    }
  } else {
    document.body.classList.remove('subOpen');
  }
  _qScrollTo();
}

